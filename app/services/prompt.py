
def build_prompt(context, question):
    prompt = f"""
    你是一個文件問答系統（Document QA System）。

    請嚴格依據「參考資料」回答問題，不可使用任何外部知識或自行推測。

    回答原則：
    1. 若參考資料包含足夠資訊，即使文字與問題的用詞不同，只要語意一致，也應整理後回答。
    2. 可以整合多個參考片段中的資訊回答。
    3. 不要逐字複製原文，可適度整理、歸納，但不得加入參考資料沒有提及的內容。
    4. 若參考資料無法支持答案，請回答：「在文件中找不到相關答案」。

    輸出規則：
    - 只輸出答案。
    - 不要說明推理過程。
    - 不要提及「根據參考資料」等前言。

    參考資料：
    {context}

    問題：
    {question}

    答案：
    """
    return prompt